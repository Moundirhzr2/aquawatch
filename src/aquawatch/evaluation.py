"""Event-level evaluation. Synthetic labels never enter ingestion or detection."""

from collections import Counter


def evaluate(predictions: list[dict], labels: list[dict]) -> dict:
    def key(item):
        return (item["meter_id"], item["kind"], item["event_date"])

    predicted, actual = set(map(key, predictions)), set(map(key, labels))
    tp, fp, fn = predicted & actual, predicted - actual, actual - predicted

    def counts(values):
        return dict(Counter(v[1] for v in sorted(values)))

    return {
        "scope": "Synthetic event benchmark; exact meter/type/event-start-date match. Not field validation.",
        "true_positives": len(tp),
        "false_positives": len(fp),
        "false_negatives": len(fn),
        "precision": len(tp) / len(predicted) if predicted else None,
        "recall": len(tp) / len(actual) if actual else None,
        "by_kind": {
            kind: {
                "tp": counts(tp).get(kind, 0),
                "fp": counts(fp).get(kind, 0),
                "fn": counts(fn).get(kind, 0),
            }
            for kind in sorted({k[1] for k in predicted | actual})
        },
        "missed_events": [dict(meter_id=m, kind=k, event_date=d) for m, k, d in sorted(fn)],
        "limitations": [
            "Synthetic events generated by this project are not independent field data.",
            "Subtle 1.5x sustained usage is intentionally included and may be missed.",
            "No claim of leak confirmation, customer fraud or financial savings.",
            "Exact event matching penalizes onset-date differences; no true-negative accuracy is reported.",
        ],
    }
